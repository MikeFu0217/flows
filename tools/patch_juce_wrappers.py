#!/usr/bin/env python3
"""Prepare Flows automation adapters in a build directory; never modify JUCE.

Only the reviewed JUCE 8.0.7 wrappers and AudioUnitSDK are accepted. Hashes use
normalized newlines so the pin works with LF and CRLF checkouts.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys


PINNED = {
    "juce_audio_plugin_client_VST3.cpp": "95bdc1644b5135130f7e024342ce401f5e6c7ab1a384933ab9042f53a02ef458",
    "juce_audio_plugin_client_AU_1.mm": "cb95a2462242f8886b3ac8748c3f3fe05338ca991c193b759d3049a804edbeb8",
    "AU/AudioUnitSDK/AUBase.h": "fd71d7001f07cbd6b874163e878714aee0632b93da8261916327cac37f1b560f",
    "AU/AudioUnitSDK/AUBase.cpp": "ccb225ffbfb6bcce9aa90d5af83389af7a7d55d2def27374bc61311cc2c6553f",
}

BRIDGE = """// Generated by Flows; implementation belongs to the native host, not JUCE.
#pragma once
#include <cmath>
namespace juce { class AudioProcessor; }
namespace flows::app {
void beginHostAutomation(juce::AudioProcessor*) noexcept;
void captureHostParameter(juce::AudioProcessor*, int parameterIndex,
                          int sampleOffset, float normalizedValue) noexcept;
void captureAUParameter(juce::AudioProcessor*, int parameterIndex,
                        unsigned int sampleOffset, float normalizedValue) noexcept;
void captureAURamp(juce::AudioProcessor*, int parameterIndex,
                   int startSampleOffset, unsigned int durationInFrames,
                   float startNormalized, float endNormalized) noexcept;
}
"""


class PatchError(RuntimeError):
    pass


def replace_once(source, before, after, label):
    count = source.count(before)
    if count != 1:
        raise PatchError(f"{label}: expected exactly one reviewed anchor, found {count}")
    return source.replace(before, after, 1)


def prepare_patches(root):
    version_file = root / "modules/juce_core/system/juce_StandardHeader.h"
    header = version_file.read_text(encoding="utf-8")
    version = []
    for macro in ("JUCE_MAJOR_VERSION", "JUCE_MINOR_VERSION", "JUCE_BUILDNUMBER"):
        match = re.search(rf"^#define\s+{macro}\s+(\d+)\s*$", header, re.MULTILINE)
        if not match:
            raise PatchError(f"Cannot read {macro} from JUCE header")
        version.append(int(match.group(1)))
    if version != [8, 0, 7]:
        raise PatchError(f"JUCE {'.'.join(map(str, version))} is not the reviewed 8.0.7 release")
    module = root / "modules/juce_audio_plugin_client"
    originals = {}
    for name, expected in PINNED.items():
        text = (module / name).read_text(encoding="utf-8")
        actual = hashlib.sha256(text.encode()).hexdigest()
        if actual != expected:
            raise PatchError(f"JUCE 8.0.7 source pin mismatch: {name}; review the adapter before updating its pin")
        originals[name] = text

    vst = originals["juce_audio_plugin_client_VST3.cpp"]
    vst = replace_once(vst, "#include <juce_core/system/juce_CompilerWarnings.h>",
                       '#include <juce_core/system/juce_CompilerWarnings.h>\n#include "flows_automation_bridge.hpp"', "VST3 bridge include")
    vst = replace_once(vst, """                if (const auto change = getPointFromQueue (paramQueue, numPoints - 1))
                {
                    if (auto* param = comPluginInstance->getParamForVSTParamID (vstParamID))
                        setValueAndNotifyIfChanged (*param, (float) change->value);
                }""", """                if (auto* param = comPluginInstance->getParamForVSTParamID (vstParamID))
                {
                    // Flows consumes every native sample offset. JUCE still mirrors the
                    // last value for its parameter/editor state below.
                    for (Steinberg::int32 point = 0; point < numPoints; ++point)
                        if (const auto change = getPointFromQueue (paramQueue, point))
                            flows::app::captureHostParameter (pluginInstance,
                                param->getParameterIndex(), change->offsetSamples,
                                static_cast<float> (change->value));

                    if (numPoints > 0)
                        if (const auto change = getPointFromQueue (paramQueue, numPoints - 1))
                            setValueAndNotifyIfChanged (*param, (float) change->value);
                }""", "VST3 native parameter queue")
    vst = replace_once(vst, """        if (pluginInstance == nullptr)
            return kResultFalse;

        if ((processSetup.symbolicSampleSize == Vst::kSample64) != pluginInstance->isUsingDoublePrecision())""", """        if (pluginInstance == nullptr)
            return kResultFalse;

        flows::app::beginHostAutomation (pluginInstance);

        if ((processSetup.symbolicSampleSize == Vst::kSample64) != pluginInstance->isUsingDoublePrecision())""", "VST3 process boundary")

    au = originals["juce_audio_plugin_client_AU_1.mm"]
    au = replace_once(au, "#include <juce_core/system/juce_CompilerWarnings.h>",
                      '#include <juce_core/system/juce_CompilerWarnings.h>\n#include "flows_automation_bridge.hpp"', "AU bridge include")
    au = replace_once(au, """                auto value = inValue / getMaximumParameterValue (param);

                if (! approximatelyEqual (value, param->getValue()))""", """                auto value = inValue / getMaximumParameterValue (param);

                flows::app::captureAUParameter (juceFilter.get(), param->getParameterIndex(),
                                                inBufferOffsetInFrames, value);

                if (! approximatelyEqual (value, param->getValue()))""", "AU immediate offset")
    au = replace_once(au, """    // No idea what this method actually does or what it should return. Current Apple docs say nothing about it.
    // (Note that this isn't marked 'override' in case older versions of the SDK don't include it)
    bool CanScheduleParameters() const override          { return false; }""", """    // Flows owns the bounded schedule. Do not call AUBase::ScheduleParameter:
    // its mParamEventList.push_back may allocate on a host's render thread.
    bool CanScheduleParameters() const override          { return true; }

    OSStatus ScheduleParameter (const AudioUnitParameterEvent* events, UInt32 count) override
    {
        if (count > 256 || (events == nullptr && count != 0) || juceFilter == nullptr)
            return kAudio_ParamError;

        // Validate the complete batch before enqueuing any event. Offsets and ramp
        // durations are kept in native units; negative ramp starts are meaningful.
        for (UInt32 i = 0; i < count; ++i)
        {
            const auto& event = events[i];
            if (event.scope != kAudioUnitScope_Global || event.element != 0)
                return kAudio_ParamError;
            auto* param = getParameterForAUParameterID (event.parameter);
            if (param == nullptr)
                return kAudioUnitErr_InvalidParameter;
            const auto maximum = getMaximumParameterValue (param);
            if (! std::isfinite (maximum) || maximum <= 0)
                return kAudio_ParamError;
            const auto valid = [maximum] (float value)
            {
                return std::isfinite (value) && value >= 0 && value <= maximum;
            };
            if (event.eventType == kParameterEvent_Immediate)
            {
                if (! valid (event.eventValues.immediate.value))
                    return kAudio_ParamError;
            }
            else if (event.eventType == kParameterEvent_Ramped)
            {
                if (! valid (event.eventValues.ramp.startValue)
                    || ! valid (event.eventValues.ramp.endValue))
                    return kAudio_ParamError;
            }
            else
                return kAudio_ParamError;
        }

        for (UInt32 i = 0; i < count; ++i)
        {
            const auto& event = events[i];
            if (event.eventType == kParameterEvent_Immediate)
            {
                // SetParameter captures the original offset before updating the
                // JUCE parameter mirror. No base scheduling vector is involved.
                const auto status = SetParameter (event.parameter, event.scope, event.element,
                    event.eventValues.immediate.value, event.eventValues.immediate.bufferOffset);
                if (status != noErr)
                    return status;
            }
            else
            {
                auto* param = getParameterForAUParameterID (event.parameter);
                const auto& ramp = event.eventValues.ramp;
                const auto maximum = getMaximumParameterValue (param);
                const auto endValue = ramp.endValue / maximum;
                flows::app::captureAURamp (juceFilter.get(), param->getParameterIndex(),
                    ramp.startBufferOffset, ramp.durationInFrames,
                    ramp.startValue / maximum, endValue);

                // Match VST3's last-point mirror without adding an offset-zero event.
                if (! approximatelyEqual (endValue, param->getValue()))
                {
                    inParameterChangedCallback = true;
                    param->setValueNotifyingHost (endValue);
                }
            }
        }
        return noErr;
    }""", "AU bounded scheduling override")
    return module, {"juce_audio_plugin_client_VST3.cpp": vst, "juce_audio_plugin_client_AU_1.mm": au}


def write_if_changed(path, text):
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def copy_if_changed(source, destination):
    destination = Path(destination)
    if destination.exists() and Path(source).read_bytes() == destination.read_bytes():
        return str(destination)
    return shutil.copy2(source, destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--juce-root", required=True, type=Path)
    parser.add_argument("--destination", type=Path, help="generated module parent inside the build directory")
    parser.add_argument("--check", action="store_true", help="validate reviewed pins and patch anchors without writing")
    args = parser.parse_args()
    root = args.juce_root.resolve()
    try:
        source, patches = prepare_patches(root)
        if args.check:
            print("JUCE 8.0.7 pins and VST3/AU adapter anchors verified; source unchanged.")
            return 0
        if args.destination is None:
            raise PatchError("--destination is required unless using --check")
        destination = args.destination.resolve()
        if destination.is_relative_to(root) or root.is_relative_to(destination):
            raise PatchError("Generated destination must be separate from the original JUCE checkout")
        marker = destination / "flows-adapter-manifest.json"
        if destination.exists() and any(destination.iterdir()) and not marker.is_file():
            raise PatchError("Refusing to overwrite a nonempty directory not owned by this generator")
        target = destination / "juce_audio_plugin_client"
        ignored = set(patches)
        shutil.copytree(source, target, dirs_exist_ok=True, copy_function=copy_if_changed,
                        ignore=lambda path, names: ignored.intersection(names) if Path(path) == source else ())
        for name, text in patches.items():
            write_if_changed(target / name, text)
        write_if_changed(target / "flows_automation_bridge.hpp", BRIDGE)
        manifest = {"schema_version": 1, "juce_version": "8.0.7", "original_module": str(source),
                    "original_sha256_normalized": PINNED,
                    "patched_sha256": {name: hashlib.sha256(text.encode()).hexdigest() for name, text in patches.items()}}
        write_if_changed(marker, json.dumps(manifest, indent=2) + "\n")
        print(f"Prepared JUCE 8.0.7 automation adapters: {target}")
        return 0
    except (OSError, PatchError) as error:
        print(f"JUCE adapter preparation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
