import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const output=ts.transpileModule(readFileSync(new URL('../src/signalDisplay.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext}}).outputText;
const {displayKey,signalDisplay,setSignalDisplay,onSignalDisplay,canSwitchDisplay}=await import(`data:text/javascript;base64,${Buffer.from(output).toString('base64')}`);
const a=displayKey('bass','raw'), b=displayKey('lead','raw');
assert.equal(signalDisplay(a,{kind:'audio'}),'spectrum');
assert.equal(signalDisplay(a,{kind:'analysis',shape:'waveform',auditionable:true}),'spectrum');
assert.equal(signalDisplay(a,{kind:'control'}),'wave');
let notifications=0;const off=onSignalDisplay(()=>notifications++);
setSignalDisplay(a,'wave');assert.equal(notifications,1);
assert.equal(signalDisplay(a,{kind:'audio'}),'wave');
assert.equal(signalDisplay(b,{kind:'audio'}),'spectrum');
assert.equal(signalDisplay(a,{shape:'mel_spectrum'}),'spectrum');
assert.equal(signalDisplay(a,{shape:'spectrum'}),'spectrum');
assert(!canSwitchDisplay({shape:'spectrum'}));assert(!canSwitchDisplay({shape:'mel_spectrum'}));assert(!canSwitchDisplay({shape:'scalar'}));
assert(canSwitchDisplay({kind:'audio',shape:'waveform'}));
off();setSignalDisplay(a,'spectrum');assert.equal(notifications,1);
console.log('Signal display: audio/probe defaults, control waveform, document isolation, shared preferences, and intrinsic scalar/spectral types passed.');
