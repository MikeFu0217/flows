import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const transpile = name => ts.transpileModule(readFileSync(new URL(`../src/${name}.ts`, import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText;
const data = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const catalogURL = data(transpile('languageCatalog'));
const { libraries, keyFields, functions, portTypes } = await import(catalogURL);
const { completeFlows } = await import(data(transpile('completionModel').replace("'./languageCatalog'", JSON.stringify(catalogURL))));
const input = 'import standard as events\nfrom lib.osc import ClassicSaw as Saw\nfrom lib.env import ClassicADSR\nfrom lib.filt import ClassicFilt\nfrom lib.mod import ClassicLFO\nfrom lib.sample import ClassicSampler\n';
const kernel = input + 'Inst.sigstream(events.event.keys.poly()) as note:\n    osc = Saw.make()\n    filt = ClassicFilt.make()\n    env = ClassicADSR.make()\n    lfo = ClassicLFO.make()\n    sampler = ClassicSampler.make()\n    raw = osc(pitch: note.pitch)\n    p = probe(raw)\n';
const complete = (text, explicit = false, samples = []) => { const pos = text.indexOf('|'); assert.ok(pos >= 0); return completeFlows(text.replace('|', ''), pos, explicit, samples); };
const labels = result => result?.options.map(option => option.label) || [];
const accept = (text, label) => {
  const result = complete(text, true), option = result.options.find(option => option.label === label);
  const source = text.replace('|', '');
  return source.slice(0, result.from) + (option.insert || option.label) + source.slice(result.to);
};
assert.equal(accept(kernel + '    x = note.pi|tch', 'pitch'), kernel + '    x = note.pitch');
assert.equal(accept(kernel + '    x = osc(lev|el: -6db)', 'level'), kernel + '    x = osc(level: -6db)');
assert.equal(accept(kernel + '    x = osc(pitch: 440h|z)', 'hz'), kernel + '    x = osc(pitch: 440hz)');
assert.equal(accept(kernel + '    q = pro|be(raw)', 'probe'), kernel + '    q = probe(raw)');
assert.equal(accept(input + 'osc = Saw.ma|ke()', 'make'), input + 'osc = Saw.make()');
assert.equal(accept(input + 'voices = events.event.keys.po|ly()', 'poly'), input + 'voices = events.event.keys.poly()');
assert.deepEqual(labels(complete(kernel + '    x = note.|')), keyFields.map(p => p.name));
assert.deepEqual(labels(complete(kernel + '    x = osc.|')), []);
assert.deepEqual(labels(complete(input + 'x = Saw.|')), ['make']);
assert.deepEqual(labels(complete(input + 'voices = events.event.keys.|')), ['poly', 'mono']);
assert.deepEqual(labels(complete(input + 'voices = events.|')), ['event']);
assert.deepEqual(labels(complete(input + 'voices = events.event.|')), ['keys']);
assert.deepEqual(labels(complete(input + 'voices = events.event.keys.poly(|')), []);
assert.deepEqual(labels(complete(input + 'voices = events.event.keys.mono(retrigger: |')), ['each_press', 'gate_rise']);
assert.deepEqual(labels(complete(kernel + '    x = env(retrigger_from: |')), ['current', 'zero']);
assert.deepEqual(labels(complete(kernel + '    x = filt(raw, mode: |')), ['lowpass', 'highpass']);
assert.deepEqual(labels(complete(kernel + '    x = lfo(shape: |')), libraries.mod.ClassicLFO.ports.find(p => p.name === 'shape').options);
assert.deepEqual(labels(complete(kernel + '    x = sampler(reverse: |')), ['false', 'true']);
assert.ok(!labels(complete(kernel + '    x = osc(pitch: note.pitch, |')).includes('pitch'));
assert.ok(!labels(complete(kernel + '    x = lfo(rate: 2hz, |')).includes('sync'));
assert.ok(labels(complete(kernel + '    x = filt(raw, |')).includes('cutoff'));
assert.ok(!labels(complete(kernel + '    x = filt(raw, |')).includes('input'));
assert.ok(labels(complete(kernel + '    diff = spec(|')).includes('p'));
assert.ok(labels(complete(kernel + '    x = |', true)).includes('raw'));
assert.ok(labels(complete(kernel + '    x = |', true)).includes('note.pitch'));
assert.equal(complete(kernel + '    # note.|'), null);
assert.equal(complete('# osc.make()\nimport standard as std\n# key.|'), null);
assert.deepEqual(labels(complete('from lib.|')), Object.keys(libraries));
assert.deepEqual(labels(complete('from lib.osc import |')), ['ClassicSine', 'ClassicSaw']);
assert.deepEqual(labels(complete('from lib.osc import ClassicSaw, |')), ['ClassicSine']);
assert.equal(complete('from lib.osc import ClassicSaw as |', true), null);
const sample = complete(kernel + '    x = sampler(file: "Sam|ples/old.wav")', false, [{ path: 'Samples/kick.wav' }]);
const original = kernel + '    x = sampler(file: "Samples/old.wav")';
assert.equal(original.slice(0, sample.from) + sample.options[0].insert + original.slice(sample.to), kernel + '    x = sampler(file: "Samples/kick.wav")');
assert.ok(complete(kernel + '    x = sampler(file: |)', true, [{ path: 'Samples/kick.wav' }]).options.some(o => o.insert === '"Samples/kick.wav"'));
assert.equal(complete(kernel + '    x = "no|completion"'), null);
const custom = input + '\nclass Tone:\n    def signal(input: audio, cutoff: hz = 900hz):\n        private = input\n        return private\n\nInst.sigstream(events.event.keys.poly()) as note:\n    tone = Tone.make()\n    x = tone(|';
assert.deepEqual(labels(complete(custom)), ['input', 'cutoff']);
assert.ok(!labels(complete(custom.replace('tone(|', '|'), true)).includes('private'));
const ports = complete(input + 'class Tone:\n    def signal(input: au|');
assert.deepEqual(labels(ports), portTypes);
const subclass = input + 'class Smooth(ClassicFilt):\n    def init:\n        self.register_knob(cutoff, default=900hz, range=(20hz, 20khz), scale=|';
assert.deepEqual(labels(complete(subclass)), ['linear', 'log']);
assert.deepEqual(labels(complete(input + 'class Smooth(ClassicFilt):\n    def init:\n        self.|')), ['register_knob']);
assert.ok(labels(complete(input + 'class Smooth(ClassicFilt):\n    def init:\n        self.register_knob(|')).includes('cutoff'));
assert.deepEqual(labels(complete(input + 'class Smooth(ClassicFilt):\n    def init:\n        self.register_knob(|')), ['cutoff', 'resonance']);
assert.ok(labels(complete(kernel + '    x = osc(pitch: 440h|')).includes('hz'));
assert.deepEqual(labels(complete(input + 'class Tone:\n    def signal(\n        cutoff: h|')), portTypes);
const metadata = complete(input + 'class Smooth(ClassicFilt):\n    def init:\n        self.register_knob(cutoff, default=900hz, range=(20hz, 20khz))\n\nInst.sigstream(events.event.keys.poly()) as note:\n    filt = Smooth.make()\n    result = filt(|');
assert.ok(metadata.signature.includes('cutoff: hz = 900hz'));
assert.ok(metadata.options.find(o => o.label === 'cutoff').info.includes('range=(20hz,20khz)'));
assert.deepEqual(labels(complete(input + 'x = Saw.make(|')), []);
assert.ok(!labels(complete(kernel + '    q = spec(p)\n    x = power(|')).includes('q'));
assert.ok(!labels(complete(kernel + '    x = |\n    future = probe(raw)', true)).includes('future'));
const unicode = complete('# 🎹 accented é\n' + kernel + '    x = note.pi|');
assert.equal(unicode.from, ('# 🎹 accented é\n' + kernel + '    x = note.').length);
for (const name of Object.keys(functions)) assert.ok(labels(complete(kernel + '    x = |', true)).includes(name));
for (const [module, classes] of Object.entries(libraries)) for (const [name, callable] of Object.entries(classes)) {
  const text = `import standard as std\nfrom lib.${module} import ${name}\nInst.sigstream(std.event.keys.poly()) as key:\n    unit = ${name}.make()\n    raw = unit(|`;
  const offered = new Set(labels(complete(text)));
  for (const port of callable.ports) assert.ok(offered.has(port.name), `${name}.${port.name} missing`);
}
console.log('Language completion: all primitives/ports/enums, aliases, scopes, typed class ports, metadata, samples, units, multiline calls and UTF-16 spans.');
